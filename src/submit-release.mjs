import {readFileSync,writeFileSync,renameSync,mkdirSync,existsSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {randomUUID,createHmac} from 'node:crypto';
const input=process.argv[2];
if(!input) throw Error('Usage: node submit-release.mjs <approved-request.json>');
const request=JSON.parse(readFileSync(resolve(input),'utf8'));
const registry=JSON.parse(readFileSync(resolve(process.env.VALVE_PROJECTS_FILE||'C:/GuardianControl/Valve/projects.json'),'utf8'));
const project=(registry.projects||[]).find(p=>p.id===request.project);
if(!project)throw Error('Unknown registered project');
if(request.approved!==true||request.publish!==true)throw Error('Explicit approval required');
if(!Array.isArray(request.paths)||!request.paths.length||request.paths.some(p=>typeof p!=='string'||!p||p.startsWith('-')||p.includes('..')||p.includes('\\')))throw Error('Invalid approved paths');
if(!Array.isArray(request.checks||[])||(request.checks||[]).some(c=>!Array.isArray(c)||!c.length||c.some(s=>typeof s!=='string')))throw Error('Invalid checks');
const keyPath=process.env.VALVE_SIGNING_KEY_FILE||'C:/ProgramData/ValvePipeline/signing.key';
const key=process.env.VALVE_SIGNING_KEY||(existsSync(keyPath)?readFileSync(keyPath,'utf8').trim():null);
if(!key||key.length<32)throw Error('Signing key unavailable');
const payload={project:project.id,repository:resolve(project.path),branch:project.branch,approved:true,publish:true,paths:request.paths,message:String(request.message||'Approved release').slice(0,160),checks:request.checks||[]};
const signature=createHmac('sha256',key).update(JSON.stringify(payload)).digest('hex');
const queue=resolve(process.env.VALVE_QUEUE_DIR||'C:/ProgramData/ValvePipeline/approved');
mkdirSync(queue,{recursive:true});
const path=join(queue,'release-'+project.id+'-'+randomUUID()+'.json');
const temp=path+'.tmp';
writeFileSync(temp,JSON.stringify({...payload,signature}),{flag:'wx',mode:0o600});
renameSync(temp,path);
console.log(JSON.stringify({status:'queued',project:project.id,file:path}));
